#!/usr/bin/env python3
"""Export a compact, source-matched successful run; never copy build binaries."""
import hashlib
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]


def main():
    source = ROOT / 'build/benchmarks'
    provenance = json.loads((source / 'provenance.json').read_text())
    verification_path = ROOT / 'build/verification/verification.json'
    verification = json.loads(verification_path.read_text())
    if not verification or not all(row['pass'] and row['exit_code'] == 0 for row in verification):
        raise SystemExit('Run make test successfully before exporting reference results')
    if not provenance['successful_runs'] or any(command['exit_code'] for command in provenance['commands']):
        raise SystemExit('Benchmark run did not complete successfully')
    for name, digest in provenance['source_sha256'].items():
        if hashlib.sha256((ROOT / name).read_bytes()).hexdigest() != digest:
            raise SystemExit(f'Source changed since benchmark execution: {name}; rerun make benchmark')
    destination = ROOT / 'level5/results/reference'
    destination.mkdir(parents=True, exist_ok=True)
    for name in ('summary.csv', 'report.md', 'provenance.json'):
        if name.endswith('.csv'):
            # Normalize only the derived reference CSV; input trace bytes/hashes stay intact.
            (destination / name).write_bytes((source / name).read_bytes().replace(b'\r\n', b'\n'))
        else:
            shutil.copy2(source / name, destination / name)
    # Raw measurements make derived ratios independently inspectable.
    for folder in ('runs', 'analysis'):
        target = destination / folder
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(source / folder, target)
    shutil.copy2(source / 'traces/manifest.json', destination / 'trace_manifest.json')
    shutil.copy2(verification_path, destination / 'verification.json')
    # Keep immutable input-bridge provenance without duplicating generated trace CSVs.
    (destination / 'README.md').write_text(
        '# Measured Phase 1 reference\n\n'
        'Generated by `make all` then `make reference`. `summary.csv` and `report.md` '
        'derive only from the retained `runs/` simulator CSVs. `provenance.json` '
        'contains commands, source hashes and tools; `trace_manifest.json` contains '
        'input/bridge provenance. Regenerate inputs with the recorded generators.\n\n'
        '`analysis/` uses the imported Level 1 analyser with 16-byte lines. '
        '`verification.json` records the separate correctness benches. '
        'Additional high-latency smoke-test logs remain in the generated build directory.\n\n'
        'These measurements describe deterministic subsystem simulation, not real inference '
        'execution or physical DRAM. No Phase 2 result is included.\n')
    print(f'Exported {provenance["successful_runs"]} measured runs to {destination.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
